import unittest

from foreman.config import ConfigError, family, load_config, order_for, parse_config


class ConfigTest(unittest.TestCase):
    def test_packaged_config_loads(self):
        config = load_config()
        self.assertEqual(config.max_review_rounds, 3)
        self.assertEqual(config.nodes["verify"].models, ())
        self.assertEqual(config.nodes["implement"].models[0], "gpt-6.1-sol-high")

    def test_review_uses_the_other_family(self):
        config = load_config()
        gpt_first = order_for("review", config, {"implement": "gpt-6.1-sol-high"})
        claude_first = order_for("review", config, {"implement": "claude-opus-5-5-high"})
        self.assertEqual(family(gpt_first[0]), "claude")
        self.assertEqual(family(gpt_first[-1]), "gpt")
        self.assertEqual(family(claude_first[0]), "gpt")
        self.assertEqual(family(claude_first[-1]), "claude")

    def test_unknown_family_is_rejected(self):
        with self.assertRaises(ConfigError):
            parse_config(
                {
                    "max_review_rounds": 3,
                    "nodes": {
                        "implement": {"role": "builder", "models": ["llama-3"]},
                    },
                }
            )


if __name__ == "__main__":
    unittest.main()
